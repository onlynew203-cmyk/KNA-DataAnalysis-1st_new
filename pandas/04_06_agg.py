import pandas as pd

df = pd.read_csv("PANDAS/data/14_hydraulic.csv",
                 encoding='utf-8')

# agg : aggregate 집계하다
# 하나의 데이터에 여러 집계 함수를 한꺼번에 적용할 때 사용

print(df.groupby('냉각기상태')['온도'].mean().round(2)) # 냉각기상태별 온도를 출력해
# 냉각기상태
# 고장    54.67
# 저하    45.46
# 정상    35.89
# --> 냉각기상태에는 '고장', '저하', '정상'이 있고, 이에 해당하는 온도를 출력함

# 냉각기상태별로 온도의 표준편차를 출력하기
print(df.groupby('냉각기상태')["온도"].std().round(2))
# 냉각기상태
# 고장    3.76
# 저하    1.47
# 정상    0.36

# 냉각기상태별 온도의 평균과 표준편자를 한번에 정리하기
print(df.groupby('냉각기상태')['온도'].agg(["mean", "std"]))
#           mean       std
# 냉각기상태                   
# 고장     54.6675  3.759595
# 저하     45.4650  1.465422
# 정상     35.8850  0.355578
# "agg -> 집계하다"를 사용해서 평균값과 표준편차를 출력함

# 더 읽기 쉬운 출력을 위한 코드를 작성해보자
print(df.groupby('냉각기상태').agg(
    평균온도 = ('온도', 'mean')
    ).round(2))
#         평균온도
# 냉각기상태       
# 고장     54.67
# 저하     45.46
# 정상     35.89

print(df.groupby('냉각기상태').agg(
    평균온도 = ('온도', 'mean'),
    온도편차 = ('온도', 'std'),
    평균진동 = ('진동', 'mean'),
    측정수 = ('온도', 'count')
    ).round(2))
#         평균온도  온도편차  평균진동  측정수
# 냉각기상태                        
# 고장     54.67  3.76  0.69   40
# 저하     45.46  1.47  0.61   40
# 정상     35.89  0.36  0.55   40



