# 단계
import pandas as pd

df = pd.read_csv("PANDAS/data/14_hydraulic_qc.csv",
                 encoding='utf-8')

# · 여러 지표 열로 상관 행렬을 만들기 # 뭐여 이게 ; 무시 ;
feat = ['지표%02d' % i for i in range(1,11)]
print(feat)
# 지표01부터 지표10까지 문자열을 자동으로 만들어서 리스트에 넣는 코드
# range(1, 11)로 1~10을 반복하면서
# 숫자를 두 자리 형식(01, 02, ... 10)으로 만들어
# 지표01 ~ 지표10을 feat 리스트에 저장

cm = df[feat].corr().round(3)
print(cm)
# cm - Correlation Matrix(상관행렬)의 줄임말

#        지표01   지표02   지표03  ...   지표08   지표09   지표10
# 지표01  1.000  0.941  0.716  ...  0.758 -0.960  0.999
# 지표02  0.941  1.000  0.801  ...  0.838 -0.961  0.935
# 지표03  0.716  0.801  1.000  ...  0.993 -0.878  0.696
# 지표04 -0.983 -0.940 -0.705  ... -0.750  0.949 -0.979
# 지표05 -0.895 -0.930 -0.950  ... -0.966  0.982 -0.882
# 지표06  0.327  0.476  0.885  ...  0.854 -0.570  0.300
# 지표07 -0.882 -0.920 -0.958  ... -0.969  0.976 -0.868
# 지표08  0.758  0.838  0.993  ...  1.000 -0.905  0.740
# 지표09 -0.960 -0.961 -0.878  ... -0.905  1.000 -0.951
# 지표10  0.999  0.935  0.696  ...  0.740 -0.951  1.000

# · 이중 반복으로 대각선을 제외한 각 쌍의 상관계수 확인
# 위 cm에서 0.4 이상의 상관관계가 크다 판단되는 경우 뽑아보기

# step 1. cm의 모든 컬럼을 순서대로 돌면서 컬럼 번호와 이름을 출력
for i in range(len(cm.columns)):
    print(f"{i}번째 컬럼 이름 {cm.columns[i]}")

data = []
# step 2. i + 1번부터 비교, 반복되는 값을 제외하고 비교하기 (1*2, 2*1을 모두 비교할 필요x)
for j in range(len(cm.columns)):
        print(f"{i}번째 컬럼 이름 {cm.columns[i]}과 비교할 {cm.columns[j]}")

        c = cm.iloc[i, j] # cm에서 i번째 행, j번째 열의 상관계수를 가져와 c에 저장

        # print(f"{i}번째 컬럼 이름 {cm.columns[i]}과 비교할 {cm.columns[j]} : {c}")

        if abs(c) > 0.4: # abs를 통해 절대값으로 비교하
            print(f"{i}번째 컬럼 이름 {cm.columns[i]}과 비교할 {cm.columns[j]} : {c} -> 강한 상관계수")


