import pandas as pd

df = pd.read_csv("PANDAS/data/14_hydraulic.csv",
                 encoding='utf-8')

# corr 상관계수
# corr = Correlation(상관관계)
# 두 변수가 서로 얼마나 같이 움직이는지를 -1 ~ 1 사이의 상관계수로 나타냄
#  1에 가까움  → 강한 양의 상관관계 (A 증가 → B도 증가하는 경향)
#  0에 가까움  → 상관관계가 약함
# -1에 가까움  → 강한 음의 상관관계 (A 증가 → B는 감소하는 경향)
# 주의: 상관관계가 높다고 해서 반드시 원인과 결과 관계인 것은 아님

cor1 = df['온도'].corr(df['진동'])
print(cor1.round(2)) # 0.93

# 세가지를 동시에 비교하자
num = df[['온도', '진동', '압력']] # df에서 온도, 진동, 압력 3개 열만 선택해서 num에 담아
print(num.corr().round(2)) # 세 변수의 상관계수를 서로 계산하고 소수점 둘째 자리까지 반올림
#       온도    진동    압력
# 온도  1.00  0.93  0.28
# 진동  0.93  1.00  0.52
# 압력  0.28  0.52  1.00

