import numpy as np

# 배열의 산술 연산
# 두 배열을 같은 위치끼리 한 번에 계산

x = np.array([1,2,3])
y = np.array([10,20,30])
print(x + y) # [11 22 33]
# shape가 같다는 전제 조건 하에 연산 가능
print(x * 2) # [2 4 6]
print(x * y) # [[10 40 90]

# 스칼라 연산 ---------------------------------
# 배열 안의 섭씨 온도들을 화씨 온도로 바꿔 출력하기
celsius = np.array([20.0, 25.0, 30.0])
f = celsius * 1.8 + 32
print(f) # [68. 77. 86.] 출력
