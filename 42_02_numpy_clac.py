# 브로드 캐스팅 ---------------------------------
# 한줄짜리 기준값이 모든 행에 퍼져서 계산
table = np.array([
    [72, 3.2],
    [78, 1.4]
])
base = np.array([70, 2.0])

# tablb의 각 행에서 기준값(base) 빼기
print(table - base)
# [[ 2.   1.2]
#  [ 8.  -0.6]] 출력

