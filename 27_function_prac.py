def report(name, temp):
    print(f"{name}의 온도는 {temp}도 입니다.")
report(name= "모터", temp= 78) # 모터의 온도는 78도 입니다.
report(temp= 78, name= "모터") # 모터의 온도는 78도 입니다.
report(name= "펌프", temp= 92) # 펌프의 온도는 92도 입니다.

