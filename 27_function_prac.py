# 실습 5. 센서 통계 함수 만들기
# 내장 함수 min(), max(), sum(), len() 활용
# ① 센서값 목록을 매개변수로 받는 함수를 정의
# ② min·max·합÷개수로 최소·최대·평균을 계산
# ③ 세 값을 쉼표로 함께 return
# ④ 돌려받은 값을 세 변수로 언패킹해 출력

def sensor_data_list(temps):
    min_temp = min(temps)
    max_temp = max(temps)
    avg_temp = sum(temps) / len(temps)
    return min_temp, max_temp, avg_temp

temps = [32, 75, 49, 21, 84, 12, 9, 102]

min_value, max_value, avg_value = sensor_data_list(temps)

print("최소:",min_value)
print("최대:",max_value)
print("평균:",avg_value)
# 최소: 9
# 최대: 102
# 평균: 48.0


