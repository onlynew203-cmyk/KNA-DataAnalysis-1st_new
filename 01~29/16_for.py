# enumerate 낱낱이 세다

temps = [33, 34, 35, 36, 37]

for t in enumerate(temps):
    print(t)
# 아래와 같이 출력
# (0, 33)
# (1, 34)
# (2, 35)
# (3, 36)
# (4, 37)
# 전달한 리스트의 모든 요소를 보여줘요
# 문제는, 형식이 (인덱스, 해당 인덱스의 요소값)으로 출력
# enumerate를 사용할때는, 변수를 2개 전달해요(아래의 예시처럼!)

for idx, t in enumerate(temps):
    print(f"idx: {idx}, t: {t}")
# enumerate는 리스트의 모든 요소를 앞에서부터 순서대로 하나씩 순회공연, 각자의 인덱스와 값을 뽑아줌   
# 아래와 같이 출력
# idx: 0, t: 33
# idx: 1, t: 34
# idx: 2, t: 35
# idx: 3, t: 36
# idx: 4, t: 37

# for idx, t in enumerate(temps):
# 위와 같이 전달하면, 리스트를 순회하며 반환하는 값(인덱스, 해당 인덱스의 값)을
# 각자 idx에 인덱스 값을 할당, t에 해당 인덱스 값을 할당해서
# 두 개의 값을 바로 사용할 수 있도록 해줌 !

for idx, t in enumerate(temps):
    print(f"현재 인덱스 :{idx}")
    print(f"{idx}인덱스의 값: {t}")
    print(f"{idx+1}번째 반복 끝")


