# 실습 사람 체온 판단
# and 사용과 if문 중첩

# 정상 체온 범위 : 36.2 ~ 36.9
user_a = float(input("체온을 입력해주세요 :"))
if user_a >= 36.2 and user_a <= 36.9:
    print("당신은 정상 체온입니다.")
else:
    if user_a > 36.9:
        print("열이 나요.")
    else:
        print("저체온입니다.")
print("체온 판단 완료")

