# 실습 숫자 맞추기 게임

answer = 50 # 정답 지정
user_answer = int(input("정답을 입력하세요."))
if user_answer == answer: # 만약에 사용자의 입력 답과 정답이 같다면
    print("정답입니다.") 
else:
    print("틀렸습니다.")
print("게임이 종료되었습니다.") # 무조건 출력

# ---------------------------
# 실습 신호등 색
# or 사용과 if문 중첩

user_input = input("색을 입력하세요.(초록, 빨강만 입력)")
if user_input == "초록" or user_input == "빨강":
    # user_input()이 "초록" 이거나 "빨강"일 때만 실행
    if user_input == "초록":
        print("건너세요") # 중첩 if문은 들여쓰기 더 주의
    # if user_input == "빨강"
    #     print("기다리세요") # 아래 else문과 동일하게 작동하지만, 비효율적 -> else문 사용 권고
    else:
        print("기다리세요")
    print("여기 코드는 사용자 입력값이 초록, 빨강일때 무조건 실행")
else:
    print("다시 입력하세요")

