# 실습 3. agg로 여러 통계 한 번에
# 리스트·이름붙이기 두 방식으로 여러 통계 요약
# 목표
# 한 번의 agg로 여러 통계를 동시에 구하기
# 단계
import pandas as pd

df = pd.read_csv("PANDAS/data/14_hydraulic.csv",
                 encoding='utf-8')

# · 교대로 그룹을 나눠 진동의 평균·표준편차·최댓값을 리스트로 한 번에
print(df.groupby('운전부하')['진동'].agg(
    ['mean', 'std', 'max']
    ).round(3))
#        mean    std    max
# 운전부하                     
# 고부하   0.602  0.083  0.779
# 저부하   0.629  0.031  0.741

# · 이름 붙이기 방식으로 설비별 평균온도·평균진동·측정수 요약
print(df.groupby('밸브상태').agg(
    평균온도 = ('온도', 'mean'),
    평균진동 = ('진동', 'mean'),
    측정수 = ('온도', 'count')
).round(2))
#        평균온도  평균진동  측정수
# 밸브상태                  
# 경미    44.86  0.62   20
# 심각    46.02  0.63   19
# 정상    45.11  0.61   61
# 지연    45.86  0.62   20

# · 두 방식의 결과 표 모양 비교
# agg 앞에 특정 컬럼을 언급하는 경우 -- 해당 컬럼의 통계값 확인
# agg 괄호 안에서 라벨링의 경우 -- 여러 컬럼의 통계값을 한 번의 출력으로 확인 가능

