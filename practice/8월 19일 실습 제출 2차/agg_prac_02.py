# 목표
# 합격·불합격 그룹의 지표 평균과 표준편차 비교
# 단계
import pandas as pd

df = pd.read_csv("PANDAS/data/14_hydraulic_qc.csv",
                 encoding='utf-8')

# · 판정 열로 그룹을 나눠 주요 지표들의 평균 집계
feats = ['지표01', '지표02', '지표03']
print(df.groupby('검사결과')[feats].mean().round(2))
#        지표01  지표02    지표03
# 검사결과                     
# 불합격   55.84  0.72  168.69
# 합격    35.91  0.55  161.02

# · 같은 그룹 기준으로 표준편차를 구해 흩어짐 비교
feats = ['지표01', '지표02', '지표03']
print(df.groupby('검사결과')[feats].std().round(2))
#       지표01  지표02  지표03
# 검사결과                  
# 불합격   1.32  0.05  7.50
# 합격    0.97  0.01  0.26
# --> 합격의 표준편차가 불합격의 표준편차보다 작음

