# 실습 1. 평균·분산·표준편차 구하기
# 전체와 라인별로 평균·분산·표준편차 구하기
# 목표
# 대푯값과 흩어짐을 나타내는 세 통계량 구하기
# 단계
import pandas as pd

df = pd.read_csv("PANDAS/data/14_hydraulic.csv",
                 encoding='utf-8')

# · 진동 열 전체의 평균·분산·표준편차를 각각 구하기
print(df['진동'].mean().round(3)) # 0.616
print(df['진동'].var().round(3)) # 0.004
print(df['진동'].std().round(3)) # 0.064

# · 표준편차를 제곱하면 분산과 같아지는지 확인
df_std = df['진동'].std().round(3) # 0.064
print((df_std ** 2).round(3)) # 0.004 --> 분산과 같은 것을 확인할 수 있다

# · 라인으로 그룹을 나눠 라인별 평균과 표준편차 비교
print(df.groupby('냉각기상태').agg(
    평균진동 = ('진동', 'mean'),
    진동편차 = ('진동', 'std'),
    측정수 = ('진동', 'count')
).round(3))
#         평균진동   진동편차  측정수
# 냉각기상태                   
# 고장     0.688  0.048   40
# 저하     0.610  0.010   40
# 정상     0.549  0.009   40


