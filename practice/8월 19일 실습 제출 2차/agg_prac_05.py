# 실습 5. 그룹별 통계량 종합
# 전체·그룹 통계와 진단표를 한 흐름으로
# 목표
# 전체 통계부터 그룹 진단표까지 한 흐름으로 종합
# 단계
import pandas as pd

df = pd.read_csv("PANDAS/data/14_hydraulic.csv",
                 encoding='utf-8')

# · 온도 열의 전체 평균과 표준편차로 기준선 파악
print(df['온도'].mean().round(2)) # 45.34
print(df['온도'].std().round(2)) # 8.04

# · 라인별 평균과 중앙값을 함께 구해 치우침 확인
print(df.groupby('냉각기상태').agg(
    평균온도 = ('온도', 'mean'),
    온도중앙값 = ('온도', 'median')
).round(2))
#         평균온도  온도중앙값
# 냉각기상태              
# 고장     54.67  55.45
# 저하     45.46  44.90
# 정상     35.89  35.90
# --> '정상' 상태에서 평균온도와 온도중앙값의 차이가 가장 적음(안정적)

# · 설비 진단표를 온도편차 순으로 정렬해 우선 점검 대상 선정
report_prac = df.groupby('밸브상태').agg(
    평균온도 = ('온도', 'mean'),
    온도편차 = ('온도', 'std'),
    평균진동 = ('진동', 'mean')
).round(2)

print(report_prac)
#        평균온도  온도편차  평균진동
# 밸브상태                   
# 경미    44.86  8.11  0.62
# 심각    46.02  8.40  0.63
# 정상    45.11  7.79  0.61
# 지연    45.86  8.93  0.62

print(report_prac.sort_values('온도편차', ascending=False))
#        평균온도  온도편차  평균진동
# 밸브상태                   
# 지연    45.86  8.93  0.62
# 심각    46.02  8.40  0.63
# 경미    44.86  8.11  0.62
# 정상    45.11  7.79  0.61

