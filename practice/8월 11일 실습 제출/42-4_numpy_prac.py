# 실습 6. 센서별 기초 통계 구하기
# 목표
# 표 모양 데이터에서 센서별(열별) 통계 계산
# 단계

import numpy as np

# · 여러 설비의 회전수·토크 이차원 배열 준비
sensor_data = np.array([
    [1200, 35.0],
    [1300, 38.0],
    [1400, 40.0],
    [1500, 42.0],
    [1600, 45.0]
])

# · axis를 열 방향으로 지정해 센서별 평균 계산
print(sensor_data.mean(axis= 0)) # [1400.   40.]

# · 센서별 표준편차 계산
print(round(sensor_data.std(), 2)) # 687.32

