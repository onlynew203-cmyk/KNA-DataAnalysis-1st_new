# 실습 1. 특정 센서·구간 추출하기
# 목표
# 회전수 배열에서 특정 시점과 일정 간격의 값 추출
# 단계

import numpy as np
# · 회전수 측정값 배열 준비
rpm = np.array([1200, 1250, 1300, 1280, 1350, 1400, 1380, 1450, 1500, 1480])

# · 인덱싱으로 첫 시점과 마지막 시점 값 꺼내기
print(rpm[0]) # 1200 첫
print(rpm[-1]) # 1480 마지막

# · 슬라이싱으로 앞 구간과 두 칸 간격 값 추출
print(rpm[::2]) # [1200 1300 1350 1380 1500]

