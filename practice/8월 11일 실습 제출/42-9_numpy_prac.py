# 실습 2. 행·열 단위로 추출하기
# 목표
# 표 모양 센서 데이터에서 특정 행과 열을 단위로 추출
# 단계

import numpy as np

# · 여러 설비의 회전수·토크를 담은 이차원 배열 준비
sensor_data = np.array([
    [1200, 35.2],
    [1350, 40.1],
    [1280, 37.5],
    [1420, 43.8],
    [1500, 46.2]
])

# · 행 인덱싱으로 특정 설비의 값 전체 꺼내기
print(sensor_data[0]) # [1200.    35.2]  # 0번째 행 전체 값

# · 열 인덱싱으로 모든 설비의 회전수 열과 토크 열 추출
print(sensor_data[:, 0]) # [1200. 1350. 1280. 1420. 1500.] # 회전수 열
print(sensor_data[:, 1]) # [35.2 40.1 37.5 43.8 46.2] # 토크 열

# 예상 결과
# 특정 설비 행, 회전수 열, 토크 열이 각각 출력