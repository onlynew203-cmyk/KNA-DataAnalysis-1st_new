# 실습 6. 여러 기준 조합 그룹
# 두 기준을 묶어 세분 그룹의 평균과 건수 확인
# 목표
# 두 기준을 조합해 단일 기준에서 안 보이던 패턴 찾기
# 단계
import pandas as pd

df = pd.read_csv("PANDAS/data/14_hydraulic.csv",
                 encoding='utf-8')
# · 라인과 교대 두 기준을 묶어 온도 평균 집계 # 온도로 바꿔서 해볼게요
# 냉각기상태, 운전부하 기준순서를 잡아서 각 그룹별 평균 온도
print(df.groupby(['냉각기상태', '운전부하'])['온도'].mean().round(2))
# 냉각기상태  운전부하
# 고장     고부하     55.51
#        저부하     54.05
# 저하     고부하     44.07
#        저부하     45.58
# 정상     고부하     35.89
# Name: 온도, dtype: float64

# · 같은 두 기준으로 size를 구해 조합별 측정 건수 확인
# 결측(null값)들이 포함되어있음을 주의 !!
print(df.groupby(['냉각기상태', '운전부하']).size())
# 냉각기상태  운전부하
# 고장     고부하     17
#        저부하     23
# 저하     고부하      3
#        저부하     37
# 정상     고부하     40 # --> 냉각기상태가 '정상'이면서 운전부하가 '고부하'인 것은 40건
# dtype: int64

# · 건수가 적은 조합의 평균은 신중히 해석
