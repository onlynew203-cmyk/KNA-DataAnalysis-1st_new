print(sensors.get("유량", 8)) # 8 --> 기본값 출력
# '유량'에 8을 넣음 -> 그대로 8 출력 / 딕셔너리에 새로운 키와 값을 추가한 것은 아님
print(type(sensors.get("유량")) ) # <class 'NoneType'>
