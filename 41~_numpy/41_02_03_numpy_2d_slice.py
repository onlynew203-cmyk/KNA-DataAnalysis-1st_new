# 2차원 슬라이싱 - 행/열 선택
# 행 전체, 열 전체, 일부 구간 잘라내기 - 콜론이 전부를 의미

import numpy as np

data = np.array([
    [83, 1.2],
    [79, 4.1],
    [97, 3.1],
    [98, 1.5]
])

# 0번째 행 전체 가져오기
print(data[0]) # [83.   1.2]
# print(data[0, :]) # [83.   1.2]

# 3번째 행 전체 가져오기
print(data[3]) # [98.   1.5]

# : == 전부를 의미
# 0번째 열 전체 가져오기
print(data[:, 0]) # [83. 79. 97. 98.]

# : == 전부를 의미
# 1번째 열 전체 가져오기
print(data[:, 1]) # [1.2 4.1 3.1 1.5]



