# 특정 시간축 배열 만들기

import numpy as np

# 특정 시작 시각과 끝 시각을 정해서
# 특정 간격 시간들이 지난다면
# 언제 언제 체크포인트가 만들어지나를
# numpy의 배열로 알아보기기

# 0 ~ 60초 사이에 5초 간격으로 체크하면 어느 지점에 체크가 되는가

checks = np.arange(0, 60, 5)
print(checks) # [ 0  5 10 15 20 25 30 35 40 45 50 55]

# ---------------------------------------------
# 실습 3. 측정 시간축 배열 만들기

# 목표
# 측정 시점을 나타내는 시간축 배열을 일정 간격으로 생성
# 단계
# · 시작값·끝값·간격을 정해 np.arange로 시점 배열 생성
# · 간격을 바꿔가며 시점 개수 변화 관찰
# · 시간축 배열 출력
# 예상 결과
# 0초부터 일정 간격으로 증가하는 측정 시점 배열 출력

check_points = np.arange(0, 120, 37) # 0초부터 120초까지 37초의 간격으로 핑 찍어줘
print(check_points) # [  0  37  74 111] 출력
